export function parseSpreadsheetCsv(csvText: string): ContentItem[] {
  if (!csvText || typeof csvText !== 'string') return [];
  const lines = csvText.split(/\r?\n/).filter((l) => l.trim().length > 0);
  if (lines.length < 2) return [];

  const headers = lines[0].split(',').map((h) => h.replace(/^"|"$/g, '').trim());
  const items: ContentItem[] = [];

  for (let i = 1; i < lines.length; i++) {
    // Regex to split comma respecting quotes
    const values = lines[i].match(/(".*?"|[^",\s]+)(?=\s*,|\s*$)/g) || lines[i].split(',');
    const cleanValues = values.map((v) => v.replace(/^"|"$/g, '').trim());

    const rowObj: any = {};
    headers.forEach((h, idx) => {
      rowObj[h] = cleanValues[idx] || '';
    });

    if (rowObj.ID || rowObj.Tema || rowObj.Klien) {
      items.push({
        ID: rowObj.ID || `gen-${Math.random().toString(36).substring(2, 9)}`,
        Klien: normalizeClientName(rowObj.Klien),
        TanggalProduksi: rowObj.TanggalProduksi || '',
        Bulan: rowObj.Bulan || '',
        Tahun: rowObj.Tahun || new Date().getFullYear(),
        Tema: rowObj.Tema || rowObj.IdeKonten || 'Konten Tanpa Judul',
        IdeKonten: rowObj.IdeKonten || '',
        Detail: rowObj.Detail || '',
        JenisKonten: rowObj.JenisKonten || 'Single Post',
        Kategori: rowObj.Kategori || (rowObj.JenisKonten === 'Reels / TikTok' ? 'Video' : 'Desain'),
        SourceReferences: rowObj.SourceReferences || '',
        MateriKonten: rowObj.MateriKonten || '',
        ProjectTools: rowObj.ProjectTools || 'Canva',
        Creator: normalizeCreatorName(rowObj.Creator),
        Status: (rowObj.Status as any) || 'New Idea',
        JadwalPosting: rowObj.JadwalPosting || '',
        File: rowObj.File || '',
        Catatan: rowObj.Catatan || '',
        FeeAmount: Number(rowObj.FeeAmount) || 0,
        CreatedAt: rowObj.CreatedAt || new Date().toISOString(),
        UpdatedAt: rowObj.UpdatedAt || new Date().toISOString(),
        ChecklistAsset: rowObj.ChecklistAsset === 'TRUE' || rowObj.ChecklistAsset === true,
        ChecklistCaption: rowObj.ChecklistCaption === 'TRUE' || rowObj.ChecklistCaption === true,
        TipeProject: rowObj.TipeProject === 'Internal' ? 'Internal' : 'Komersil',
        TanggalApprove: rowObj.TanggalApprove || '',
      });
    }
  }

  return items;
}
