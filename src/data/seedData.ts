export function normalizeClientName(name: string | undefined): string {
  if (!name) return '';
  const trimmed = name.trim();
  const lower = trimmed.toLowerCase();
  if (lower.includes('inovasi pangan')) return 'INOVASI PANGAN LESTARI';
  if (lower.includes('keripik sayur')) return 'KERIPIK SAYUR ID';
  if (lower.includes('feed kreatif') || lower.includes('feedkreatif')) return 'FEED KREATIF';
  return trimmed.toUpperCase();
}

export function normalizeCreatorName(name: string | undefined): string {
  if (!name) return 'Belum ditugaskan';
  const trimmed = name.trim();
  const lower = trimmed.toLowerCase();
  if (lower.includes('adissa')) return 'Adissa Rifdah Aulia';
  if (lower.includes('aldrien')) return 'Aldrien Andriansyah';
  if (lower.includes('labib')) return 'Muhammad Labib Azka';
  if (lower.includes('febrina')) return 'Febrina Putri K';
  if (lower.includes('lalu') || lower.includes('mahendra')) return 'Lalu Mahendra Ali Akbar';
  return trimmed;
}

